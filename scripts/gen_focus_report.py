#!/usr/bin/env python3
"""Generate ``docs/benchmarks/batch-focus.md`` from measured artifacts.

Every number in the report is computed here from the raw summaries of
the clean-commit focus rounds (A/B), the full-space holdout round, the
model-validation metrics, and the frozen table/calibration profiles.
Hand-editing the markdown is not supported: re-run this script.

Usage::

    python scripts/gen_focus_report.py \
        --focus results/p800/batch_focus_a results/p800/batch_focus_b \
        --holdout results/p800/batch_holdout \
        --validation results/p800/model_validation.json \
        --out docs/benchmarks/batch-focus.md
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.xpu.config import DesignSpace  # noqa: E402
from src.xpu.selector import GUARD_PCT  # noqa: E402

BASELINE = "incumbent_m4_folded"
NON_MODEL_PREFIX = ("vendor", "selected", "baseline")


# ---------------------------------------------------------------- helpers

def _load(path: Path) -> dict:
    with open(path) as f:
        return json.load(f)


def _fmt(ms: float, st: float | None = None) -> str:
    if st is None:
        return f"{ms:.4f}"
    return f"{ms:.4f}±{st:.4f}"


def _z(a: float, b: float, sa: float, sb: float) -> float:
    """How far apart are two medians, in pooled-stdev units?"""
    pool = math.sqrt((sa ** 2 + sb ** 2) / 2.0) if (sa or sb) else 0.0
    return abs(a - b) / pool if pool > 0 else float("inf") if a != b else 0.0


def _shape_key(sh: dict) -> str:
    return f"N{sh['N']}B{sh['batch']}_{sh['direction']}"


def _model_candidates(sh: dict) -> dict:
    return {k: v for k, v in sh["candidates"].items()
            if not k.startswith(NON_MODEL_PREFIX)}


def _winner(sh: dict) -> tuple[str, float, float]:
    cand = _model_candidates(sh)
    k = min(cand, key=lambda n: cand[n]["median_ms"])
    row = cand[k]
    return k, row["median_ms"], float(row.get("stdev_ms") or 0.0)


def _baseline_ms(sh: dict) -> float:
    return float(sh["candidates"][BASELINE]["median_ms"])


def _vendor_ms(sh: dict) -> float:
    return float(sh["candidates"]["vendor"]["median_ms"])


def _m2_points(sh: dict) -> dict[tuple[int, int], float]:
    """All published-space m2 measurements of one shape row."""
    out = {}
    for k, v in sh["candidates"].items():
        if k == "m2_batch":
            out[(64, 8)] = float(v["median_ms"])
        elif k.startswith("m2_t"):
            rest = k[len("m2_t"):]
            t_s, r_s = rest.split("_rows")
            out[(int(t_s), int(r_s))] = float(v["median_ms"])
    return out


def _git(*args: str) -> str:
    return subprocess.check_output(["git", *args], cwd=ROOT,
                                   text=True).strip()


# ------------------------------------------------------------------ data

def _pairs(focus_dirs: list[Path]) -> list[tuple[str, dict, dict]]:
    runs = [(d.name, _load(d / "summary.json")) for d in focus_dirs]
    if len(runs) != 2:
        raise SystemExit("expected exactly two focus rounds (A and B)")
    (na, a), (nb, b) = runs
    keys = [_shape_key(s) for s in a["shapes"]]
    if keys != [_shape_key(s) for s in b["shapes"]]:
        raise SystemExit(f"{na} and {nb} cover different shapes")
    return [(k, sa, sb) for k, sa, sb in zip(keys, a["shapes"], b["shapes"])]


